import React, { forwardRef } from "react";
import { cn } from "@/lib/utils";

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  variant?: "default" | "elevated" | "interactive" | "flat" | "charcoal";
}

export const Card = forwardRef<HTMLDivElement, CardProps>(
  ({ className, variant = "default", ...props }, ref) => {
    return (
      <div
        ref={ref}
        className={cn(
          "rounded-2xl border text-foreground transition-all duration-300",
          variant === "default" &&
            "bg-white dark:bg-[#1A1D24] border-border/80 shadow-soft",
          variant === "elevated" &&
            "bg-white dark:bg-[#1A1D24] border-border/60 shadow-lg shadow-black/5 dark:shadow-black/20",
          variant === "interactive" &&
            "bg-white dark:bg-[#1A1D24] border-border/80 shadow-soft hover:-translate-y-1 hover:shadow-card-hover hover:border-[#FF6B35]/40 cursor-pointer",
          variant === "flat" &&
            "bg-white dark:bg-[#1A1D24] border-border/80 shadow-none",
          variant === "charcoal" &&
            "bg-[#111318] text-white border-white/10 shadow-soft",
          className
        )}
        {...props}
      />
    );
  }
);

Card.displayName = "Card";

